# 006: the four quivers share the quiver glyph — the tint and the
# tooltip carry the difference; every other relic draws its own.
_RELIC_ICON = {"poison_arrows": "quiver", "slowing_arrows": "quiver",
               "piercing_arrows": "quiver", "fire_arrows": "quiver",
               "strip_potion": "veil_draught"}


def icon_key(slug: str, kind: str = "") -> str:
    """Resolve an inventory entry to an icon key. Weapons draw their
    line's silhouette (blade / bow / staff, focuses their diamond); other
    gear resolves by slot, apothecary items by slug, relics by their own
    glyphs, the rest is a pack."""
    if slug in _RELIC_ICON:
        return _RELIC_ICON[slug]
    if slug in _GRIDS:
        return slug
    if kind in ("weapon", "shield"):
        from . import economy
        g = economy.FORGE.get(slug)
        line = getattr(g, "line", "") if g is not None else ""
        if kind == "weapon":
            return {"archer": "bow", "sorcerer": "staff"}.get(line, "weapon")
        if g is not None and g.slot == "shield" and line == "sorcerer":
            return "focus"
        return "shield"
    if kind in ("armor", "shoes"):
        return kind
    return "pack"


@lru_cache(maxsize=None)
def icon_data_url(key: str) -> str:
    """Inline SVG data URL for the 16×16 mask — white ink, crisp edges.
    Unknown keys draw the pack crate (never a broken cell)."""
    grid = _GRIDS.get(key) or _GRIDS["pack"]
    rects = []
    for y, row in enumerate(grid):
        x = 0
        while x < 16:
            if row[x] == "#":
                run = x
                while run < 16 and row[run] == "#":
                    run += 1
                rects.append(f'<rect x="{x}" y="{y}" '
                             f'width="{run - x}" height="1"/>')
                x = run
            else:
                x += 1
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" '
           'width="32" height="32" shape-rendering="crispEdges" '
           f'fill="#fff">{"".join(rects)}</svg>')
    return "data:image/svg+xml;charset=utf-8," + quote(svg, safe="")
